import assert from 'node:assert/strict';
export async function runWechatHexoUi(page) {
  const original = await page.evaluate(()=>window.fixture.read());
  const commits = await page.evaluate(()=>window.fixture.hexoCommitted());
  await page.evaluate(async()=>{
    window.fixture.replace('---\npub_id: local-id\nsource_file: "[[source]]"\n---\n## 公众号独立标题\n\n　　保留这一段 **Markdown 正文**。\n\n> 引用排版\n\n```ts\n  const a = 1;\n  next(a);\n```\n\n![Cover](../../assets/cover.png)');
    await window.fixture.view.refresh();
  });
  const createButton = () => page.getByRole('button',{name:'生成 Hexo 稿',exact:true});
  const create = () => createButton().click();
  const dialog = page.getByRole('dialog');
  const mode = (value='markdown') => dialog.getByRole('radio',{name:value==='layout'?'保留公众号排版':'普通 Markdown',exact:true});
  const save = () => dialog.getByRole('button',{name:'确认生成 Hexo 草稿',exact:true});
  await create();
  assert.equal(await mode().isChecked(),true);
  assert.match(await dialog.innerText(),/将新建 Hexo 草稿/);
  assert.match(await dialog.locator('.ep-wechat-hexo-preview pre').innerText(),/## 公众号独立标题/);
  assert.equal(await dialog.locator('.ep-wechat-hexo-preview h2').count(),0);
  await dialog.getByRole('button',{name:'取消',exact:true}).click();
  assert.equal(await page.evaluate(()=>window.fixture.hexoCommitted()),commits);
  await create();
  await save().click();
  await dialog.waitFor({state:'hidden'});
  const markdown = await page.evaluate(()=>window.fixture.hexoGenerated());
  assert.match(markdown,/　　保留这一段 \*\*Markdown 正文\*\*/);
  assert.match(markdown,/!\[Cover\]\(\/picture\//);
  assert.doesNotMatch(markdown,/easy-pub-wechat-layout|!important|<section|style=|blob:|easy-pub-image:/);
  await page.getByRole('status').filter({hasText:'Hexo 稿已保存'}).waitFor();
  await create();
  await mode('layout').check();
  await dialog.locator('.ep-wechat-hexo-preview h2').waitFor();
  assert.equal(await dialog.locator('.ep-wechat-hexo-preview h2').innerText(),'公众号独立标题');
  assert.match(await dialog.locator('.ep-wechat-hexo-preview pre').innerText(),/const a = 1/);
  await page.evaluate(()=>window.fixture.setReadDelay(200));
  assert.equal(await createButton().isDisabled(),true,'Generating again is unavailable until the current workbench operation completes');
  await save().click();
  await dialog.waitFor({state:'hidden'});
  const html = await page.evaluate(()=>window.fixture.hexoGenerated());
  assert.match(html,/easy-pub-wechat-layout/);assert.match(html,/!important/);
  assert.match(html,/src="\/picture\//);assert.doesNotMatch(html,/blob:|easy-pub-image:/);
  await create();
  // A late result from an older selection must never become the saved plan.
  await page.evaluate(()=>window.fixture.setReadDelay(250));
  await mode('layout').check();
  assert.equal(await save().isDisabled(),true);
  await page.evaluate(()=>window.fixture.setReadDelay(1));
  await mode().check();
  await dialog.getByRole('status').filter({hasText:'请核对所选格式'}).waitFor();
  await page.waitForTimeout(300);
  assert.equal(await mode().isChecked(),true);
  assert.equal(await dialog.locator('.ep-wechat-hexo-preview h2').count(),0);
  assert.match(await dialog.locator('.ep-wechat-hexo-preview pre').innerText(),/\*\*Markdown 正文\*\*/);
  await page.evaluate(()=>window.fixture.setReadDelay(0));
  await page.evaluate(()=>window.fixture.replace(window.fixture.read()+'\nExternal edit'));
  await save().click();
  await dialog.getByRole('status').filter({hasText:'已变化'}).waitFor();
  assert.equal(await page.evaluate(()=>window.fixture.hexoCommitted()),commits+2);
  await dialog.getByRole('button',{name:'取消',exact:true}).click();
  await page.evaluate(async text=>{window.fixture.replace(text);await window.fixture.view.refresh();},original);
  console.log('WeChat to Hexo browser: default Markdown/layout choices, safe previews, cancel, image URLs, save, late-mode and stale guards passed.');
}
