// Execute via Obsidian CLI eval in the explicitly authorized Sandbox vault.
// Leaves isolated test notes/attachments for visual inspection. No remote writes.
async function runSandbox(app) {
  if (app.vault.adapter.getBasePath().toLowerCase() !== 'e:\\obsidian\\sandbox') throw Error('Wrong vault');
  const plugin = app.plugins.plugins['easy-pub'];
  if (!plugin) throw Error('EasyPub not loaded');
  const root = `EasyPub-test-${Date.now()}`;
  const result = { root, checks: [], remoteWrites: 0 };
  window.easyPubSandboxResult = result;
  const assert = (value, label) => { if (!value) throw Error(label); result.checks.push(label); };
  const sleep = ms => new Promise(resolve => setTimeout(resolve, ms));
  const wait = async predicate => { for (let i=0;i<150;i++) { if (predicate()) return; await sleep(100); } throw Error('Timed out: '+predicate); };
  const button = (view, label) => { const el = [...view.contentEl.querySelectorAll('button')].find(b=>b.textContent===label); if (!el) throw Error('Missing button: '+label); el.click(); };
  await app.vault.createFolder(root);
  await app.vault.createFolder(root+'/assets');
  await app.vault.createFolder(root+'/other');
  const canvas = document.createElement('canvas'); canvas.width=1440; canvas.height=900;
  const ctx=canvas.getContext('2d'); ctx.fillStyle='#164f40';ctx.fillRect(0,0,1440,900);
  ctx.fillStyle='#f3c572';ctx.fillRect(750,0,690,900);ctx.fillStyle='#ffffff';ctx.font='bold 100px sans-serif';ctx.fillText('EasyPub',90,200);
  const bytes=await (await new Promise(resolve=>canvas.toBlob(resolve,'image/png'))).arrayBuffer();
  await app.vault.createBinary(root+'/assets/cover.png',bytes);
  ctx.clearRect(0,0,1440,900);ctx.fillStyle='#236795';ctx.fillRect(200,100,600,500);
  const transparent=await (await new Promise(resolve=>canvas.toBlob(resolve,'image/png'))).arrayBuffer();
  await app.vault.createBinary(root+'/other/cover.png',transparent);
  const title='Sandbox-'+Date.now();
  const source=await app.vault.create(root+'/source.md',`---\ntitle: ${title}\n---\n# 真实工作台测试\n\n正文保留标记\n\n![[${root}/assets/cover.png]]\n\n![透明同名图](other/cover.png)\n\n![重复图](assets/cover.png)\n\n| 项目 | 状态 |\n|---|---|\n| 表格 | 完好 |\n\n- 一级\n  - 二级\n\n\`\`\`ts\n    const indent = 1;\n\`\`\`\n\n[[${root}/source|内部链接]]`);
  await wait(()=>app.metadataCache.getFirstLinkpathDest(root+'/assets/cover.png',source.path));
  await app.workspace.getLeaf(false).openFile(source);
  const platform={id:'wechat',name:'微信公众号',path:'微信公众号',hasSubFolders:false,autoUrl:false,isExternal:false};
  await plugin.preparePublish(platform);
  const view=app.workspace.getLeavesOfType('easy-pub-wechat')[0]?.view;
  assert(view?.file && view.file!==source,'生成独立本地稿并打开真实工作台');
  await wait(()=>!view.busy && !view.stale);
  result.draft=view.file.path;
  assert(view.prepared.issues.length===0,'原生正文预检无误报');
  assert(view.prepared.images.length===2,'重复图片复用，两个同名附件分别解析');
  assert(view.prepared.images.some(i=>i.mime==='image/png'),'透明图片保留 PNG');
  assert(view.prepared.images.every(i=>i.localPath.startsWith(root+'/')),'重定位引用指向原附件');
  assert(view.preview.querySelector('table') && view.preview.querySelector('ul ul'),'真实表格与嵌套列表');
  const draft=view.file;
  const initial=await app.vault.read(draft);
  await app.vault.modify(source,(await app.vault.read(source))+'\n源文章新改动不应导入');
  await app.workspace.getLeaf(false).openFile(source);
  await plugin.preparePublish(platform);
  assert((await app.vault.read(draft))===initial && view.file===draft,'源文章变化只打开已有成稿，不覆盖、不换绑定');
  await app.vault.modify(draft,initial+'\n\n本地稿独立编辑');
  button(view,'暂停刷新');
  await sleep(900);
  assert(!view.preview.textContent.includes('本地稿独立编辑') && view.stale,'真实文件事件后暂停取消排队刷新');
  button(view,'刷新预览'); await wait(()=>!view.busy && !view.stale);
  assert(view.preview.textContent.includes('本地稿独立编辑'),'暂停期间手动刷新');
  button(view,'信息、配图与封面');
  const input=view.contentEl.querySelector('.epw-field input');input.value='本地已编辑标题';input.dispatchEvent(new Event('input'));
  await app.vault.modify(draft,(await app.vault.read(draft))+'\n\n设置期间再改正文');
  button(view,'刷新预览');await wait(()=>!view.busy && !view.stale);
  assert(view.article.title==='本地已编辑标题' && view.dirty,'正文刷新保留未保存标题');
  const zoom=view.contentEl.querySelector('.epw-zoom');zoom.value='4';zoom.dispatchEvent(new Event('input'));
  assert(view.contentEl.querySelector('.epw-crop-resolution').textContent.includes('清晰度较低'),'裁剪按有效分辨率警告');
  const square=JSON.stringify(view.article.cropSquare),wide=JSON.stringify(view.article.cropWide);
  button(view,'保存设置并刷新');await wait(()=>!view.busy && !view.dirty && !view.stale);
  assert(JSON.stringify(view.article.cropWide)===wide && JSON.stringify(view.article.cropSquare)===square,'真实 front matter 保存两个裁剪');
  assert((await app.vault.read(draft)).includes('设置期间再改正文'),'设置保存不丢正文');
  await app.vault.modify(draft,(await app.vault.read(draft))+'\n\n![缺失测试](missing.png)');
  button(view,'刷新预览');await wait(()=>!view.busy && !view.stale);
  assert(view.prepared.issues.some(s=>s.includes('missing.png')) && view.syncButton.disabled,'缺失图片明确报错并阻止同步');
  await app.vault.modify(draft,(await app.vault.read(draft)).replace('\n\n![缺失测试](missing.png)',''));
  button(view,'刷新预览');await wait(()=>!view.busy && !view.stale);
  assert(view.prepared.issues.length===0,'修复引用后恢复');
  const after=new Uint8Array(await app.vault.readBinary(app.vault.getAbstractFileByPath(root+'/assets/cover.png')));
  assert(after.every((v,i)=>v===new Uint8Array(bytes)[i]) && after.length===bytes.byteLength,'原附件字节未改写');
  const saved=await app.vault.read(draft);
  const leaf=view.leaf; await leaf.detach();
  assert(view.closed && !view.prepared,'关闭真实工作台清理资源');
  await plugin.openWechatDraft(draft);
  const reopened=app.workspace.getLeavesOfType('easy-pub-wechat')[0].view;
  await wait(()=>!reopened.busy && !reopened.stale);
  assert((await app.vault.read(draft))===saved && JSON.stringify(reopened.article.cropWide)===wide,'重新打开恢复本地设置');
  await app.workspace.getLeaf(false).openFile(draft);
  button(reopened,'正文预览');
  result.complete=true;
  return result;
}
